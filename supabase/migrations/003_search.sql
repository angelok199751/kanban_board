-- =====================================================================
-- QA Flow · миграция 003 · поиск по содержимому карточек
-- =====================================================================
-- Что делает: добавляет в tasks столбец search_text: описание карточки
-- без HTML-тегов. Он вычисляется базой сам и обновляется при каждом
-- изменении description_html; вручную его не заполняют.
--
-- Что НЕ делает: ничего не удаляет, существующие данные не меняет.
-- Выполнять после 001 и 002, один раз. Повторный запуск безопасен (if not exists).
-- =====================================================================

alter table public.tasks
  add column if not exists search_text text
  generated always as (regexp_replace(description_html, '<[^>]*>', ' ', 'g')) stored;
